"""Storage interface of the one native prepare/publish/checkpoint protocol.

RunJournal is the local implementation. Queue task scopes implement these same
operations in the queue database, alongside leases, completion and budgets.
This interface neither schedules work nor maintains a second progress ledger.
"""
from typing import Protocol


class NativeCommitStore(Protocol):
    def execution_guard(self, fence): ...
    def begin_commit(self, fence, action_id, sequence, intent): ...
    def prepare_commit(self, fence, commit_id, prepared): ...
    def execution_commit(self, commit_id): ...
    def execution_commits(self, action_id): ...
    def publish_receipt(self, db, commit_id, sink_id, receipt): ...
    def confirm_commit(self, fence, commit_id, *, expected, status): ...
    def reserve_budgets(self, fence, reservation_id, charges): ...
    def finalize_source_commit(self, fence, commit_id): ...
